#!/usr/bin/env node
/**
 * supabase/setup.sql is every migration in supabase/migrations, in order, as one file to paste into the Supabase SQL editor.
 * It used to be kept by hand and had drifted from the migrations (its policies were written differently, and it lacked
 * migration 003). It is now generated, so there is one source of truth.
 *
 *   node scripts/build-setup-sql.mjs          rewrite supabase/setup.sql
 *   node scripts/build-setup-sql.mjs --check  exit 1 if supabase/setup.sql is out of date (CI and the tests run this)
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDir = join(root, "supabase", "migrations");
const target = join(root, "supabase", "setup.sql");

const HEADER = `-- ============================================================
-- Everest Smart Traders — full database setup
-- ============================================================
-- GENERATED by scripts/build-setup-sql.mjs from supabase/migrations/*.sql: do not edit by hand.
-- Paste into the Supabase SQL editor on a new project, or run the files in supabase/migrations in order.
-- (An existing database that already ran the earlier migrations needs only the newer files.)
`;

export function buildSetupSql() {
  const files = readdirSync(migrationsDir).filter((f) => f.endsWith(".sql")).sort();
  const parts = files.map((f) => `\n-- ---- ${f} ----\n\n${readFileSync(join(migrationsDir, f), "utf8").trim()}\n`);
  return HEADER + parts.join("");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const wanted = buildSetupSql();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(target, "utf8");
    } catch {
      /* missing counts as out of date */
    }
    if (current !== wanted) {
      console.error("supabase/setup.sql is out of date. Run: node scripts/build-setup-sql.mjs");
      process.exit(1);
    }
    console.log("supabase/setup.sql is up to date.");
  } else {
    writeFileSync(target, wanted);
    console.log(`wrote supabase/setup.sql (${wanted.split("\n").length} lines)`);
  }
}
